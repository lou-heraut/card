def render(lang="fr"):
    """Le catalogue d'une langue et son décompte, sans rien écrire.

    Séparé de `main` pour qu'un test puisse comparer le fichier écrit à
    ce qu'il devrait être : une garde qui régénère elle-même n'en serait
    pas une.
    """
    cards = _find_cards(_DEFAULT_CARD_DIR, None)
    sections = defaultdict(list)   # "domaine / phénomène" -> [(nom, meta, rel)]

    for name, path in sorted(cards.items()):
        rel = path.relative_to(_DEFAULT_CARD_DIR)
        # rel.parts = (domaine, phénomène-ou-purpose, forme, fichier)
        section = " / ".join(p.replace("-", " ") for p in rel.parts[:2])
        # _meta_frame (et non _meta_rows) : le catalogue doit montrer la
        # forme par défaut d'une fiche à placeholders, jamais l'accolade.
        meta = _meta_frame(load_card(path))
        sections[section].append((name, meta, rel))

    n_cards = len(cards)
    n_vars = sum(len(m) for grp in sections.values() for _, m, _ in grp)

    def _sect_key(section):
        dom = section.split(" / ")[0]
        return (_DOMAIN_ORDER.index(dom) if dom in _DOMAIN_ORDER else 99, section)

    ordered = sorted(sections, key=_sect_key)

    lines = list(_ENTETE[lang]) + [_SOMMAIRE[lang], ""]
    for section in ordered:
        lines.append(f"- [{section}](#{_anchor(section)}) "
                     f"({len(sections[section])})")
    lines.append("")

    for section in ordered:
        lines += [f"## {section}", "",
                  _COLONNES[lang], "|---|---|---|---|---|---|---|"]

        def _form(row):
            return str(row[1]["output_fr"].iloc[0])

        for name, meta, rel in sorted(
                sections[section],
                key=lambda r: (_FORM_ORDER.get(_form(r), 9), r[0])):
            label = str(meta[f"name_{lang}"].iloc[0]) or str(meta["name_en"].iloc[0])
            # `unite()` est celle de la figure : le catalogue et `card.info`
            # doivent écrire une unité de la même façon, et lisiblement
            # (m³·s⁻¹ plutôt que m^{3}.s^{-1}).
            unit = unite(meta[f"unit_{lang}"].iloc[0])
            inputs = _inputs(meta["input_vars"].iloc[0])
            exp = "⚠" if bool(meta["is_experimental"].iloc[0]) else ""

            def facet(col):
                vals = [str(v) for v in meta[col] if str(v)]
                uniq = sorted(set(vals), key=vals.index)
                return ", ".join(uniq)

            # Les facettes tiennent dans une cellule : on les scanne
            # ensemble, et trois colonnes de plus poussaient la table
            # hors de l'écran.
            facettes = " · ".join(f for f in (facet(f"output_{lang}"),
                                              facet(f"season_{lang}"),
                                              facet(f"aspect_{lang}")) if f)
            # La colonne `variables` ne dit quelque chose que si la fiche
            # sort autre chose que son propre nom : ailleurs elle répétait
            # la première colonne.
            variables = [str(v) for v in meta["variable_en"]]
            sorties = ", ".join(variables) if variables != [name] else ""
            link = (f"[{name}](https://github.com/lou-heraut/card/"
                    f"blob/main/src/card/cards/{rel.as_posix()})")
            lines.append(
                f"| {link} | {label} | {sorties} | {facettes} "
                f"| {unit} | {inputs} | {exp} |"
            )
        lines.append("")

    return "\n".join(lines), n_cards, n_vars, len(sections)






