#
# Quatre rendus du même corpus, quatre publics, et c'est voulu :
#   docs/CARDS.md, CARDS.fr.md   le dépôt, lisible sur GitHub sans rien bâtir
#   docs/catalogue.md            le site : une entrée par VARIABLE, filtrable
