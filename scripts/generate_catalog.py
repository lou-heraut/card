def _inputs(raw):
    """Les colonnes que `data` doit contenir, sans leur unité.

    L'unité de chaque entrée est dans `inputs.yaml` et dans la fiche : la
    répéter ici allongeait des lignes déjà larges, pour une information
    qu'on ne scanne pas. On lit `Q, T`, pas `Q [m^{3}.s^{-1}], T [°C]`.
    """
    out = []
    for var in str(raw).split(","):
        var = var.strip()
        if var:
            out.append(var)
    return ", ".join(out)


